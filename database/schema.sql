CREATE DATABASE IF NOT EXISTS enigma_capital_nova CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE enigma_capital_nova;
CREATE TABLE IF NOT EXISTS players (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 username VARCHAR(60) NOT NULL,
 email VARCHAR(190) NOT NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS saves (
 player_id BIGINT UNSIGNED NOT NULL PRIMARY KEY,
 payload LONGTEXT NOT NULL,
 scenes_visited SMALLINT UNSIGNED NOT NULL DEFAULT 0,
 clues_found SMALLINT UNSIGNED NOT NULL DEFAULT 0,
 endings_found SMALLINT UNSIGNED NOT NULL DEFAULT 0,
 updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 CONSTRAINT fk_saves_player FOREIGN KEY (player_id) REFERENCES players(id) ON DELETE CASCADE
) ENGINE=InnoDB;
